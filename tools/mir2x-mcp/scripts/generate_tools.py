"""Generate fixed typed signatures from the accepted C++ contract; no runtime exec."""

import argparse
import json
import subprocess
import sys
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
SOURCE = PROJECT.parents[1] / "contracts/ai-bridge/v1/contract.schema.json"
TARGET = PROJECT / "src/mir2x_mcp"
SCHEMA = json.loads(SOURCE.read_text("utf-8"))


def hint(schema):
    if "$ref" in schema:
        assert schema["$ref"] == "#/$defs/context"
        return "GameContext"
    if "enum" in schema:
        return "Literal[" + ", ".join(repr(value) for value in schema["enum"]) + "]"
    kind = schema["type"]
    if kind == "array":
        assert schema["items"]["type"] == "object"
        return f"Annotated[list[TradeItem], Field(max_length={schema['maxItems']})]"
    typename = {"integer": "int", "string": "str", "boolean": "bool"}[kind]
    constraints = ["strict=True"]
    for source, dest in (
        ("minimum", "ge"),
        ("maximum", "le"),
        ("minLength", "min_length"),
        ("maxLength", "max_length"),
        ("pattern", "pattern"),
    ):
        if source in schema:
            constraints.append(f"{dest}={schema[source]!r}")
    return f"Annotated[{typename}, Field({', '.join(constraints)})]"


def generate():
    TARGET.joinpath("contract.schema.json").write_bytes(SOURCE.read_bytes())
    models = [
        '"""Generated by scripts/generate_tools.py; do not edit."""',
        "from typing import Annotated",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
    ]
    for name, schema in (
        ("GameContext", SCHEMA["$defs"]["context"]),
        (
            "TradeItem",
            SCHEMA["x-methods"]["game_trade_offer"]["params"]["properties"]["items"]["items"],
        ),
    ):
        models += [
            f"class {name}(BaseModel):",
            '    model_config = ConfigDict(extra="forbid", strict=True)',
        ]
        models += [f"    {key}: {hint(value)}" for key, value in schema["properties"].items()]
        models.append("")
    TARGET.joinpath("models.py").write_text("\n".join(models) + "\n", "utf-8")
    lines = [
        '"""Generated fixed tools. Validate raw arguments before SDK conversion."""',
        "from typing import Annotated, Literal",
        "from pydantic import Field",
        "from mcp_types import CallToolResult, ToolAnnotations",
        "from .models import GameContext, TradeItem",
        "",
        "def register_tools(server, bridge):",
    ]
    for name, meta in SCHEMA["x-methods"].items():
        params = meta["params"]
        branches = params.get("oneOf", [params])
        properties = {}
        required = set(branches[0]["required"])
        for branch in branches:
            properties.update(branch["properties"])
            required.intersection_update(branch["required"])
        if meta["action"]:
            definition = SCHEMA["$defs"][name + "Request"]["properties"]
            for key in ("request_id", "context", "timeout_ms"):
                properties[key] = definition[key]
                required.add(key)
        write = meta["write"]
        description = meta["description"]
        if meta["action"]:
            description += "；返回操作ID后查询进展，unknown不得自动重试。"
        lines += [
            "    @server.tool(",
            f"        name={name!r}, description={description!r},",
            "        annotations=ToolAnnotations(",
            f"            read_only_hint={not write}, destructive_hint={write},",
            f"            idempotent_hint={name == 'game_stop' or not write},",
            "            open_world_hint=False),",
            "    )",
            f"    async def {name}(",
        ]
        if properties:
            lines.append("        *,")
        for key, value in properties.items():
            field_type = hint(value)
            if key in required:
                default = ""
            elif "default" in value:
                default = f" = {value['default']!r}"
            else:
                # Only omission uses the None sentinel; raw validation forbids explicit null.
                # Keep str as the SDK annotation or its JSON pre-parser rewrites "null"/"[]".
                if value.get("type") != "string":
                    field_type += " | None"
                default = " = None"
            lines.append(f"        {key}: {field_type}{default},")
        lines += ["    ) -> CallToolResult:", f"        return await bridge.tool({name!r}, {{"]
        lines += [f"            {key!r}: {key}," for key in properties]
        lines += ["        })", ""]
    TARGET.joinpath("tools.py").write_text("\n".join(lines), "utf-8")
    subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--config",
            str(PROJECT / "pyproject.toml"),
            str(TARGET / "tools.py"),
            str(TARGET / "models.py"),
        ],
        check=True,
    )
    subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--fix",
            "--config",
            str(PROJECT / "pyproject.toml"),
            str(TARGET / "tools.py"),
            str(TARGET / "models.py"),
        ],
        check=True,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="从共享契约生成固定Python签名与契约副本")
    parser.add_argument("--output-dir", type=Path, default=TARGET)
    TARGET = parser.parse_args().output_dir.resolve()
    TARGET.mkdir(parents=True, exist_ok=True)
    generate()
